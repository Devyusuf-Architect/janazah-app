const providerIds = (user) => (user?.providerData || []).map((p) => p.providerId);
const usesPassword = (user) => providerIds(user).includes('password');
const usesGoogle = (user) => providerIds(user).includes('google.com');

function signInMethodLabel(user) {
  const ids = providerIds(user);
  if (ids.includes('google.com') && ids.includes('password')) return 'Google and password';
  if (ids.includes('google.com')) return 'Google';
  if (ids.includes('password')) return 'Email and password';
  return ids[0] || 'Unknown';
}

function initialsFor(user) {
  const source = (user?.displayName || user?.email || '').trim();
  if (!source) return '?';
  const words = source.split(/[\s._-]+/).filter(Boolean);
  if (words.length > 1) return (words[0][0] + words[1][0]).toUpperCase();
  return source.slice(0, 2).toUpperCase();
}

function profileSection(panel, ctx, repaint) {
  const user = auth.currentUser || ctx.user;

  const avatar = user.photoURL
    ? el('img', { class: 'set-avatar', src: user.photoURL, alt: '', referrerpolicy: 'no-referrer' })
    : el('span', { class: 'set-avatar set-avatar--initials', text: initialsFor(user) });

  const name = el('input', {
    class: 'field', id: 'displayName', maxlength: 80, value: user.displayName || '',
    placeholder: 'How you would like to be addressed',
  });
  const save = el('button', { class: 'btn btn--primary btn--small' }, 'Save name');
  save.addEventListener('click', async () => {
    save.disabled = true;
    try {
      await updateProfile(auth.currentUser, { displayName: name.value.trim() });
      toast('Name updated.');
      repaint();
    } catch (err) {
      toast(friendlyError(err), 'error');
      save.disabled = false;
    }
  });

  panel.append(
    group('Profile',
      el('div', { class: 'set-identity' }, [
        avatar,
        el('div', {}, [
          el('p', { class: 'set-identity__name', text: user.displayName || 'No name set' }),
          el('p', { class: 'set-identity__mail', text: user.email || '' }),
        ]),
      ]),
      el('p', { class: 'hint' },
        user.photoURL
          ? 'Your picture comes from the account you sign in with. Change it '
            + 'there and it changes here.'
          : 'Your initials stand in for a picture. Nobody else on Ta’ziyah '
            + 'sees this — it appears only to you, in the corner of your own '
            + 'screen.'),
      el('div', { class: 'field-group' }, [
        el('label', { class: 'label', for: 'displayName', text: 'Display name' }),
        name,
        el('p', { class: 'hint', text: 'Used to greet you and to draw your initials.' }),
      ]),
      el('div', { class: 'set-actions' }, [save]),
    ),

    group('What is not here',
      el('p', { class: 'hint' },
        'Ta’ziyah keeps no record of you beyond your sign-in account: there '
        + 'is no profile stored on our side to hold a phone number or an '
        + 'uploaded photo, and adding one would mean collecting personal '
        + 'details this service does not need. Masjids you follow and your '
        + 'alert settings live on this device.'),
    ),
  );
}

