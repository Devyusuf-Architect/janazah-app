/**
 * The existing alerts panel, unchanged: it already handles push support, the
 * iPhone install requirement and the page-only fallback, and duplicating that
 * logic here is how the two would drift apart.
 */
function alertsPanelHolder(repaint) {
  const holder = el('div', {});
  import('./alerts-panel.js')
    .then(({ alertsPanel }) => holder.replaceChildren(alertsPanel(repaint)))
    .catch((err) => {
      console.error('alerts-panel', err);
      holder.replaceChildren(el('p', { class: 'hint', text: 'Alert options are unavailable.' }));
    });
  return holder;
}

