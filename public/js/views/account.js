// Settings.
//
// One page, six sections, a menu down the side. Everything here is either a
// real Firebase Auth operation or a device-local preference; there is no user
// document behind any of it, because this application deliberately stores
// nothing about a person server-side. Two consequences worth stating plainly
// rather than working around: preferences do not follow somebody to another
// device, and fields that would need a user record — a phone number, an
// uploaded avatar — are not offered rather than being offered and quietly
// dropped.
//
// Two-step sign-in is the substantial part. It is genuine Firebase multi-factor
// TOTP: a secret generated by Firebase, enrolled against the account, and
// demanded by Firebase at the next sign-in. Nothing about it is a flag in a
// database that a determined person could set for themselves.

