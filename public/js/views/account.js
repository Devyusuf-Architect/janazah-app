function enrolledFactors() {
  try {
    return multiFactor(auth.currentUser).enrolledFactors || [];
  } catch {
    return [];
  }
}

/**
 * What to show when Firebase refuses.
 *
 * Three things a person can act on — sign in again, confirm your email, that
 * code was wrong — and then a catch-all. The catch-all is deliberately a
 * closed list rather than an open one: anything else that comes back from
 * Firebase during setup is our configuration problem, not theirs, and
 * "Missing phoneEnrollmentInfo" or a pointer to a file in this repository is
 * not something they can do anything about. They get one plain sentence; the
 * detail goes to the console for whoever looks after the project.
 *
 * @param {Error} err
 * @param {object} [options]
 * @param {boolean} [options.duringSetup] Treat unrecognised errors as a
 *   configuration fault rather than passing the raw text through.
 */
function unavailableMessage(err, { duringSetup = false } = {}) {
  const code = err?.code || '';
  if (code === 'auth/requires-recent-login') {
    return 'For security, sign out and sign in again before changing this.';
  }
  if (code === 'auth/invalid-verification-code' || code === 'auth/invalid-verification-id') {
    return 'The code could not be verified. Please try again.';
  }
  if (code === 'auth/unverified-email') {
    return 'Confirm your email address first. We can send you a link from the '
         + 'Account section above.';
  }
  const looksLikeConfiguration = code === 'auth/operation-not-allowed'
    || code === 'auth/unsupported-first-factor'
    || code === 'auth/admin-restricted-operation'
    || code === 'auth/invalid-argument'
    || /identity platform|not enabled|admin-restricted|totp|enrollmentinfo/i
      .test(err?.message || '');

  if (duringSetup || looksLikeConfiguration) {
    console.error(
      'Two-factor authentication is unavailable. Check that the Firebase '
      + 'project has the Identity Platform upgrade with TOTP multi-factor '
      + 'enabled: Firebase console > Authentication > Sign-in method > '
      + 'Advanced > Multi-factor authentication > Authenticator app (TOTP). '
      + 'Note that the Firebase Auth emulator does not implement TOTP '
      + 'enrolment at all, so this always fails locally.', err);
    return 'Two-factor authentication is temporarily unavailable.';
  }
  return friendlyError(err);
}

function twoFactorGroup(panel, ctx, repaint, enrolled) {
  const on = enrolled.length > 0;
  const user = auth.currentUser || ctx.user;

  const setUp = el('button', { class: 'btn btn--primary btn--small' },
    'Set up two-factor authentication');
  setUp.addEventListener('click', () => startEnrolment(setUp, repaint));

  return group('Two-factor authentication',
    row('Status',
      'An authenticator app generates a six-digit code that is needed '
      + 'alongside your password.',
      on ? pill('On', 'verified') : pill('Off', 'warn')),

    on
      ? [
        ...enrolled.map((factor) => el('p', { class: 'hint' },
          factor.enrollmentTime
            ? `Authenticator added ${new Date(factor.enrollmentTime).toLocaleDateString('en-CA')}.`
            : 'Authenticator app enrolled.')),
        el('div', { class: 'set-actions' }, [
          el('button', {
            class: 'btn btn--small btn--danger',
            onclick: () => confirmDisable(enrolled[0], repaint),
          }, 'Turn off'),
        ]),
      ]
      : [
        el('p', { class: 'hint' },
          'It protects this account even if your password is exposed '
          + 'elsewhere, which is worth the extra step, especially if this '
          + 'account can publish notices in a masjid’s name.'),
        // Firebase refuses to enrol a second factor on an unconfirmed
        // address, and rightly so: without it, somebody who signed up with an
        // inbox they do not own could lock the real owner out of the account.
        // Better to say so here than to let them press the button and be
        // refused after reading three steps.
        user?.emailVerified === false
          ? el('p', { class: 'notice-strip notice-strip--warn' },
            'Confirm your email address first. Use “Send confirmation link” '
            + 'in the Account section above, then come back.')
          : el('div', { class: 'set-actions' }, [setUp]),
      ],
  );
}

/**
 * Enrolment, in one modal, in the order the person experiences it: what this
 * is, then the code to scan, then the six digits back.
 *
 * Every step is real Firebase multi-factor: the secret comes from
 * TotpMultiFactorGenerator against a live multi-factor session, and enrolment
 * only succeeds if the code the authenticator produced verifies against it.
 */
async function startEnrolment(button, repaint) {
  button.disabled = true;
  const original = button.textContent;
  button.textContent = 'Preparing…';

  let secret;
  try {
    const session = await multiFactor(auth.currentUser).getSession();
    secret = await TotpMultiFactorGenerator.generateSecret(session);
  } catch (err) {
    // Anything at all from this call is a configuration fault as far as the
    // person is concerned: they have pressed one button and cannot act on
    // whatever Firebase said.
    toast(unavailableMessage(err, { duringSetup: true }), 'error');
    button.disabled = false;
    button.textContent = original;
    return;
  }
  button.disabled = false;
  button.textContent = original;

  const account = auth.currentUser.email || 'Ta’ziyah account';
  let uri = '';
  try {
    uri = secret.generateQrCodeUrl(account, ISSUER);
  } catch {
    uri = '';
  }

  const body = el('div', { class: 'mfa' });
  const error = el('p', { class: 'form-error', hidden: true });
  const code = el('input', {
    class: 'field', id: 'totp-code', inputmode: 'numeric',
    autocomplete: 'one-time-code', maxlength: 6, placeholder: '123456',
  });

  const confirm = el('button', { class: 'btn btn--primary' }, 'Verify and turn on');
  confirm.addEventListener('click', async () => {
    error.hidden = true;
    const digits = code.value.replace(/\D/g, '');
    if (digits.length !== 6) {
      error.hidden = false;
      error.textContent = 'Enter the six digits from your authenticator app.';
      code.focus();
      return;
    }
    confirm.disabled = true;
    try {
      const assertion = TotpMultiFactorGenerator.assertionForEnrollment(secret, digits);
      await multiFactor(auth.currentUser).enroll(assertion, 'Authenticator app');
      closeModal();
      showEnabled(repaint);
    } catch (err) {
      error.hidden = false;
      error.textContent = err?.code === 'auth/invalid-verification-code'
        ? 'The code could not be verified. Please try again. Codes change '
          + 'every 30 seconds, so use the one showing now.'
        : unavailableMessage(err);
      confirm.disabled = false;
    }
  });
  code.addEventListener('keydown', (event) => {
    if (event.key === 'Enter') { event.preventDefault(); confirm.click(); }
  });

  let qr = null;
  if (uri) {
    try {
      // Drawn here rather than fetched from an image service: that URI carries
      // the shared secret for this account, and handing it to a third party is
      // the one thing this feature must never do.
      qr = qrSvg(uri, { size: 190, label: 'Scan this with your authenticator app' });
    } catch (err) {
      console.error('qr', err);
      qr = null;
    }
  }

  body.append(
    el('p', { class: 'mfa__lede' },
      'Protect your Ta’ziyah account with an authenticator app. It generates '
      + 'a six-digit code that changes every 30 seconds.'),

    el('ol', { class: 'mfa__steps' }, [
      el('li', { text: 'Open Google Authenticator, Microsoft Authenticator, Authy, or the authenticator built into your password manager.' }),
      el('li', { text: 'Scan the code below, or enter the setup key by hand.' }),
      el('li', { text: 'Type the six digits it shows.' }),
    ]),

    qr
      ? el('div', { class: 'mfa__qr' }, [qr])
      : el('p', { class: 'notice-strip notice-strip--warn' },
        'The code could not be drawn. Use the setup key below instead — it '
        + 'works exactly the same way.'),

    el('details', { class: 'mfa__manual' }, [
      el('summary', { text: 'Can’t scan? Enter the key by hand' }),
      el('p', { class: 'hint', text: `Account: ${account}` }),
      el('p', { class: 'mono mfa__key', text: formatKey(secret.secretKey) }),
      el('p', { class: 'hint', text: 'Type this into your authenticator app as a time-based key.' }),
    ]),

    el('div', { class: 'field-group' }, [
      el('label', { class: 'label', for: 'totp-code', text: 'Six-digit code' }),
      code,
    ]),
    error,
  );

  showModal('Set up two-factor authentication', body, {
    actions: [
      el('button', { class: 'btn', onclick: () => closeModal() }, 'Cancel'),
      confirm,
    ],
  });
  code.focus();
}

/** Grouped in fours: a 32-character key is unreadable as one run. */
function formatKey(key) {
  return String(key || '').replace(/(.{4})/g, '$1 ').trim();
}

function showEnabled(repaint) {
  const body = el('div', { class: 'mfa mfa--done' }, [
    el('div', { class: 'mfa__tick' }, [icon('check', { size: 26 })]),
    el('p', { class: 'mfa__lede', text: 'Two-factor authentication is on.' }),
    el('p', { class: 'hint' },
      'From now on, signing in will ask for a code from your authenticator '
      + 'app as well as your password. Keep the app installed — without it '
      + 'you will not be able to sign in.'),
  ]);
  showModal('Two-factor authentication enabled', body, {
    actions: [el('button', {
      class: 'btn btn--primary',
      onclick: () => { closeModal(); repaint(); },
    }, 'Done')],
  });
}

/**
 * Turning it off is a two-step decision, not a toggle. Somebody who taps the
 * wrong thing on a phone should not silently lose their second factor.
 */
function confirmDisable(factor, repaint) {
  const confirmCheck = el('input', { type: 'checkbox', id: 'mfa-off-confirm' });
  const remove = el('button', { class: 'btn btn--danger' }, 'Turn off');
  remove.disabled = true;
  confirmCheck.addEventListener('change', () => { remove.disabled = !confirmCheck.checked; });

  remove.addEventListener('click', async () => {
    remove.disabled = true;
    try {
      await multiFactor(auth.currentUser).unenroll(factor);
      closeModal();
      toast('Two-factor authentication turned off.');
      repaint();
    } catch (err) {
      toast(unavailableMessage(err), 'error');
      remove.disabled = false;
    }
  });

  showModal('Turn off two-factor authentication?', el('div', {}, [
    el('p', {
      text: 'Your account will be protected by its password alone. If that '
          + 'password is exposed anywhere else, somebody could sign in as you.',
    }),
    el('label', { class: 'check check--consent', for: 'mfa-off-confirm' }, [
      confirmCheck,
      el('span', { text: 'I understand, and I want to turn it off.' }),
    ]),
  ]), {
    actions: [
      el('button', { class: 'btn', onclick: () => closeModal() }, 'Keep it on'),
      remove,
    ],
  });
}

