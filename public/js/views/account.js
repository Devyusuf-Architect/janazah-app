// ---------------------------------------------------------------- the shell

export function renderAccount(mount, ctx) {
  mount.replaceChildren();

  const wanted = new URLSearchParams(location.search).get('section');
  let active = SECTIONS.some((s) => s.key === wanted) ? wanted : 'profile';

  const nav = el('nav', { class: 'settings-nav', 'aria-label': 'Settings sections' });
  const panel = el('div', { class: 'settings-panel' });
  // Follows whichever section is current, in a column on a desktop and a row
  // on a phone: the marker carries both offsets, so it does not need to know
  // which way round the menu is.
  stopIndicator?.();
  stopIndicator = slideIndicator(nav, { activeSelector: '.settings-nav__item.is-active' });

  // Only the panel is repainted when a section changes or a preference is
  // saved. Re-rendering the page would lose scroll position and the open
  // section, which is the thing that makes a settings screen feel cheap.
  const show = (key) => {
    active = key;
    paintNav();
    const section = SECTIONS.find((s) => s.key === key);
    panel.replaceChildren();
    panel.classList.remove('is-entering');
    void panel.offsetWidth;
    panel.classList.add('is-entering');
    section.render(panel, ctx, () => show(key));
  };

  function paintNav() {
    nav.replaceChildren(...SECTIONS.map((section) => {
      const item = el('button', {
        class: `settings-nav__item${section.key === active ? ' is-active' : ''}`,
        type: 'button',
        'aria-current': section.key === active ? 'page' : null,
        onclick: () => show(section.key),
      }, [icon(section.icon, { size: 17 }), el('span', { text: section.label })]);
      return item;
    }));
  }

  mount.append(
    el('div', { class: 'page-head' }, [el('h1', { text: 'Settings' })]),
    el('div', { class: 'settings' }, [nav, panel]),
  );
  show(active);
}

// ------------------------------------------------------------------ pieces

function group(title, ...children) {
  return el('section', { class: 'set-group' }, [
    el('h2', { class: 'set-group__title', text: title }),
    ...children.flat().filter(Boolean),
  ]);
}

/** One labelled row: description on the left, control on the right. */
function row(label, description, control) {
  return el('div', { class: 'set-row' }, [
    el('div', { class: 'set-row__text' }, [
      el('p', { class: 'set-row__label', text: label }),
      description ? el('p', { class: 'set-row__desc', text: description }) : null,
    ]),
    el('div', { class: 'set-row__control' }, control),
  ]);
}

/** A read-only fact, with an optional status pill. */
function factRow(label, value, pill = null) {
  return el('div', { class: 'set-row' }, [
    el('div', { class: 'set-row__text' }, [
      el('p', { class: 'set-row__label', text: label }),
      el('p', { class: 'set-row__desc set-row__value', text: value }),
    ]),
    pill ? el('div', { class: 'set-row__control' }, pill) : null,
  ]);
}

const pill = (text, tone = 'muted') =>
  el('span', { class: `chip chip--${tone}`, text });

/**
 * A switch. A real checkbox underneath, so it is reachable by keyboard and
 * announced as a switch, with the visible part drawn in CSS.
 */
function toggle(checked, onchange, labelText) {
  const input = el('input', { type: 'checkbox', class: 'switch__input', checked: checked ? true : null });
  input.setAttribute('role', 'switch');
  input.setAttribute('aria-label', labelText);
  input.addEventListener('change', () => onchange(input.checked, input));
  return el('label', { class: 'switch' }, [input, el('span', { class: 'switch__track' })]);
}

function choice(options, value, onchange, labelText) {
  const select = el('select', { class: 'field field--inline' },
    options.map((o) => el('option', {
      value: String(o.value), text: o.label, selected: String(o.value) === String(value),
    })));
  select.setAttribute('aria-label', labelText);
  select.addEventListener('change', () => onchange(select.value));
  return select;
}

