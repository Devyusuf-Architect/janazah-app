/**
 * Deleting the account.
 *
 * Blocked for somebody who owns an organization, and not as a formality: the
 * organization record names them as owner, notices carry their uid as author,
 * and the audit trail points at them. Deleting the account would leave a
 * verified masjid nobody can administer and an audit trail attributed to an
 * account that no longer exists.
 */
async function confirmDelete() {
  const body = el('div', {}, [el('p', { class: 'muted', text: 'Checking…' })]);
  showModal('Delete your account?', body, {
    actions: [el('button', { class: 'btn', onclick: () => closeModal() }, 'Cancel')],
  });

  let owned = [];
  try {
    owned = (await store.myOrganizations(auth.currentUser.uid))
      .filter((org) => org.ownerUid === auth.currentUser.uid);
  } catch (err) {
    console.error('myOrganizations', err);
  }

  if (owned.length) {
    body.replaceChildren(
      el('p', {
        text: `You are the owner of ${owned.map((o) => o.name).join(', ')}. `
            + 'An organization cannot be left without an owner, and the notices '
            + 'it has published are attributed to your account.',
      }),
      el('p', { class: 'hint' },
        'Transfer ownership to another member of staff, or contact a platform '
        + 'administrator, before deleting this account.'),
    );
    return;
  }

  const confirmCheck = el('input', { type: 'checkbox', id: 'delete-confirm' });
  const remove = el('button', { class: 'btn btn--danger' }, 'Delete permanently');
  remove.disabled = true;
  confirmCheck.addEventListener('change', () => { remove.disabled = !confirmCheck.checked; });
  remove.addEventListener('click', async () => {
    remove.disabled = true;
    try {
      // The account's own /users document goes first, while there is still a
      // signed-in session allowed to delete it. Afterwards nobody can: the
      // rules open that document to its own account and to nobody else, so a
      // record left behind here would be unreachable forever.
      await deleteAccountRecord();
      await deleteUser(auth.currentUser);
      closeModal();
      toast('Your account has been deleted.');
    } catch (err) {
      body.append(el('p', { class: 'form-error' },
        err?.code === 'auth/requires-recent-login'
          ? 'For security, sign out and sign in again, then delete the account.'
          : friendlyError(err)));
      remove.disabled = false;
    }
  });

  body.replaceChildren(
    el('p', {
      text: 'Your sign-in account will be removed permanently. You can still '
          + 'read Janazah notices afterwards without an account.',
    }),
    el('p', { class: 'hint' },
      'Masjids you follow and your alert settings are stored on this device, '
      + 'not in your account, so they are unaffected. Clear them from '
      + 'Settings if you want them gone too.'),
    el('label', { class: 'check check--consent', for: 'delete-confirm' }, [
      confirmCheck,
      el('span', { text: 'I understand this cannot be undone.' }),
    ]),
  );
  showModal('Delete your account?', body, {
    actions: [
      el('button', { class: 'btn', onclick: () => closeModal() }, 'Cancel'),
      remove,
    ],
  });
}
