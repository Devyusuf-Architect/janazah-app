function locationSection(panel, ctx, repaint) {
  const settings = loc.settings();
  const available = loc.canUseLocation();

  const enable = el('button', { class: 'btn btn--small btn--primary' }, 'Turn on');
  enable.addEventListener('click', async () => {
    enable.disabled = true;
    enable.textContent = 'Finding your location…';
    try {
      loc.update({ enabled: true });
      await loc.requestPosition();
      push.syncTopics().catch((err) => console.error('syncTopics', err));
      repaint();
    } catch (err) {
      loc.disable();
      toast(err.message, 'error');
      enable.disabled = false;
      enable.textContent = 'Turn on';
    }
  });

  panel.append(
    group('Location',
      row('Nearby alerts',
        'Used in your browser only, to measure distance to notices this page '
        + 'already shows.',
        settings.enabled
          ? el('button', {
            class: 'btn btn--small btn--danger',
            onclick: () => {
              loc.disable();
              push.syncTopics().catch((err) => console.error('syncTopics', err));
              toast('Location turned off and the stored position erased.');
              repaint();
            },
          }, 'Turn off')
          : enable),

      settings.enabled
        ? row('Distance', 'How far away a Janazah can be and still reach you.',
          choice(loc.RADIUS_OPTIONS.map((o) => ({ value: o.km, label: o.label })),
            settings.radiusKm, (value) => {
              loc.update({ radiusKm: Number(value) });
              push.syncTopics().catch((err) => console.error('syncTopics', err));
              toast('Distance updated.');
            }, 'Alert distance'))
        : null,

      factRow('Permission', permissionLabel(available, settings)),
    ),

    group('What is stored',
      el('p', { class: 'hint' },
        'Only your most recent position, on this device, overwritten each '
        + 'time. Nothing is appended, so no history of where you have been '
        + 'can build up, and turning this off erases it immediately. Your '
        + 'position is never sent to us or to any masjid.'),
      el('p', { class: 'hint' }, [
        'More detail is on the ',
        el('a', { class: 'link', href: '/privacy', text: 'privacy page' }),
        '.',
      ]),
    ),
  );
}

function permissionLabel(available, settings) {
  if (!available) {
    return window.isSecureContext
      ? 'This browser does not offer location access.'
      : 'Browsers only allow location over a secure (https) connection.';
  }
  if (!settings.enabled) return 'Not in use.';
  if (!settings.last) return 'On, but no position has been taken yet.';
  return loc.isStale(settings.last)
    ? 'On. The stored position is a few hours old.'
    : 'On. A recent position is stored on this device.';
}

