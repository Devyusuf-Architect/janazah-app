// Resolve a manifest merger conflict on the FCM notification colour.
//
// Two things declare `com.google.firebase.messaging.default_notification_color`
// and the merger refuses to pick one:
//
//   expo-notifications      writes it into the app manifest, pointing at the
//                           colour configured in app.config.ts (#14503f).
//   @react-native-firebase  declares its own in the library manifest.
//     /messaging
//
// `tools:replace="android:resource"` tells the merger the app's value wins,
// which is the answer we want: the brand green is the whole reason the entry
// exists, and the library's default is a placeholder.
//
// This is a config plugin rather than an edit to
// android/app/src/main/AndroidManifest.xml, and that distinction matters here.
// The android/ directory is generated by `expo prebuild` and is gitignored, so
// a hand edit works exactly once and disappears the next time anyone runs
// prebuild with --clean, on a machine that has never seen the fix, or in CI.
// The failure then looks like a new bug rather than a lost patch.
//
// It must run after expo-notifications, which is what creates the element, so
// it is listed last in the plugins array in app.config.ts.

const { withAndroidManifest } = require('@expo/config-plugins');

const META_DATA_NAME = 'com.google.firebase.messaging.default_notification_color';

module.exports = function withNotificationColorFix(config) {
  return withAndroidManifest(config, (mod) => {
    const application = mod.modResults?.manifest?.application?.[0];
    const metaData = application?.['meta-data'];

    if (!Array.isArray(metaData)) {
      // Nothing to fix, and nothing to fail over: a manifest without an
      // application block is a different problem and prebuild will say so.
      return mod;
    }

    const entry = metaData.find(
      (item) => item?.$?.['android:name'] === META_DATA_NAME,
    );

    if (!entry) {
      // expo-notifications is not configured with an icon or colour, so the
      // element does not exist and there is no conflict to resolve. Adding
      // tools:replace for an absent element would itself fail the merge.
      return mod;
    }

    entry.$['tools:replace'] = 'android:resource';
    return mod;
  });
};
